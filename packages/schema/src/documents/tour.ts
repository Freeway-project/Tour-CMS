import { defineArrayMember, defineField, defineType } from 'sanity';

export const tour = defineType({
  name: 'tour',
  title: 'Tour',
  type: 'document',
  groups: [
    { name: 'content', title: 'Content', default: true },
    { name: 'pricingBooking', title: 'Pricing & booking' },
    { name: 'media', title: 'Media' },
    { name: 'seo', title: 'SEO' },
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Tour name',
      type: 'string',
      group: 'content',
      description: 'The name customers see, for example "Niagara Falls Day Tour from Toronto".',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'URL slug',
      type: 'slug',
      group: 'content',
      description:
        'The end of the page address. Generated from the tour name — edit only if needed.',
      options: {
        source: 'title',
        maxLength: 96,
        isUnique: (slug, context) => context.defaultIsUnique(slug, context),
      },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'status',
      title: 'Status',
      type: 'string',
      group: 'content',
      description: 'Hidden tours are not shown anywhere on the website.',
      options: {
        list: [
          { title: 'Active', value: 'active' },
          { title: 'Seasonal', value: 'seasonal' },
          { title: 'Hidden', value: 'hidden' },
        ],
        layout: 'radio',
      },
      initialValue: 'active',
    }),
    defineField({
      name: 'shortDescription',
      title: 'Short description',
      type: 'text',
      rows: 3,
      group: 'content',
      description:
        'One or two sentences shown on tour cards and in search results. Keep it under 200 characters.',
      validation: (rule) => rule.required().max(200),
    }),
    defineField({
      name: 'body',
      title: 'Full description',
      type: 'array',
      group: 'content',
      description: 'The main text on the tour page. Add photos between paragraphs where useful.',
      of: [
        defineArrayMember({
          type: 'block',
          styles: [
            { title: 'Normal', value: 'normal' },
            { title: 'Heading 2', value: 'h2' },
            { title: 'Heading 3', value: 'h3' },
          ],
          lists: [
            { title: 'Bulleted list', value: 'bullet' },
            { title: 'Numbered list', value: 'number' },
          ],
          marks: {
            annotations: [
              {
                name: 'link',
                title: 'Link',
                type: 'object',
                fields: [
                  defineField({
                    name: 'href',
                    title: 'Link URL',
                    type: 'url',
                    validation: (rule) => rule.required(),
                  }),
                  defineField({
                    name: 'openInNewTab',
                    title: 'Open in a new tab',
                    type: 'boolean',
                    initialValue: false,
                  }),
                ],
              },
            ],
          },
        }),
        defineArrayMember({ type: 'imageWithAlt', title: 'Image' }),
      ],
    }),
    defineField({
      name: 'heroImage',
      title: 'Hero image',
      type: 'imageWithAlt',
      group: 'media',
      description: 'The large photo at the top of the tour page.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'gallery',
      title: 'Photo gallery',
      type: 'array',
      group: 'media',
      description: 'Extra photos shown further down the tour page. Up to 20.',
      of: [defineArrayMember({ type: 'imageWithAlt' })],
      validation: (rule) => rule.max(20),
    }),
    defineField({
      name: 'durationHours',
      title: 'Duration (hours)',
      type: 'number',
      group: 'content',
      description: 'How long the whole tour takes, in hours.',
      validation: (rule) => rule.required().min(0),
    }),
    defineField({
      name: 'startTime',
      title: 'Start time',
      type: 'string',
      group: 'content',
      description: 'When the tour usually leaves, for example "8:00 AM".',
    }),
    defineField({
      name: 'groupSizeMax',
      title: 'Maximum group size',
      type: 'number',
      group: 'content',
      description: 'The most guests on one departure.',
      validation: (rule) => rule.min(1),
    }),
    defineField({
      name: 'priceTiers',
      title: 'Prices',
      type: 'array',
      group: 'pricingBooking',
      description: 'One row per customer type. Add at least one price.',
      of: [defineArrayMember({ type: 'priceTier' })],
      validation: (rule) => rule.required().min(1),
    }),
    defineField({
      name: 'fromPriceCad',
      title: 'From price (CAD)',
      type: 'number',
      group: 'pricingBooking',
      description:
        'The lowest price across the price tiers, in Canadian dollars. Calculated automatically from the prices above — do not edit.',
      readOnly: true,
    }),
    defineField({
      name: 'highlights',
      title: 'Highlights',
      type: 'array',
      group: 'content',
      description: 'Short selling points shown as a list. Up to 8.',
      of: [defineArrayMember({ type: 'string' })],
      validation: (rule) => rule.max(8),
    }),
    defineField({
      name: 'included',
      title: 'What is included',
      type: 'array',
      group: 'content',
      description: 'Items included in the price, for example "Hotel pickup and drop-off".',
      of: [defineArrayMember({ type: 'string' })],
    }),
    defineField({
      name: 'notIncluded',
      title: 'What is not included',
      type: 'array',
      group: 'content',
      description: 'Items guests pay for separately, for example "Gratuities".',
      of: [defineArrayMember({ type: 'string' })],
    }),
    defineField({
      name: 'itinerary',
      title: 'Itinerary',
      type: 'array',
      group: 'content',
      description: 'The stops in order, from pickup to drop-off.',
      of: [defineArrayMember({ type: 'itineraryStop' })],
    }),
    defineField({
      name: 'pickupLocations',
      title: 'Pickup locations',
      type: 'array',
      group: 'content',
      description: 'Places where guests can join this tour.',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'pickupLocation' }] })],
    }),
    defineField({
      name: 'faqs',
      title: 'Frequently asked questions',
      type: 'array',
      group: 'content',
      of: [defineArrayMember({ type: 'faqItem' })],
    }),
    defineField({
      name: 'reviews',
      title: 'Reviews',
      type: 'array',
      group: 'content',
      description: 'Customer reviews to show on this tour page.',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'review' }] })],
    }),
    defineField({
      name: 'booking',
      title: 'Booking',
      type: 'object',
      group: 'pricingBooking',
      description: 'Where the "Book now" button sends guests.',
      options: { collapsible: true, collapsed: false },
      fieldsets: [{ name: 'bookingDetails', title: 'Booking details' }],
      fields: [
        defineField({
          name: 'provider',
          title: 'Booking provider',
          type: 'string',
          fieldset: 'bookingDetails',
          description: 'The system that handles bookings and payments.',
          options: {
            list: [
              { title: 'FareHarbor', value: 'fareharbor' },
              { title: 'Bókun', value: 'bokun' },
              { title: 'Peek', value: 'peek' },
              { title: 'No online booking', value: 'none' },
            ],
            layout: 'radio',
          },
          initialValue: 'none',
        }),
        defineField({
          name: 'productId',
          title: 'Product ID',
          type: 'string',
          fieldset: 'bookingDetails',
          description: 'The tour ID in the booking system. Leave empty if you do not use one.',
        }),
        defineField({
          name: 'bookingUrl',
          title: 'Booking URL',
          type: 'url',
          fieldset: 'bookingDetails',
          description: 'The page guests land on when they start a booking.',
        }),
      ],
    }),
    defineField({
      name: 'seasonalNote',
      title: 'Seasonal note',
      type: 'string',
      group: 'content',
      description: 'Optional note about the season, for example "Boat cruise runs May–October".',
    }),
    defineField({
      name: 'seo',
      title: 'SEO',
      type: 'seo',
      group: 'seo',
    }),
  ],
  preview: {
    select: {
      title: 'title',
      subtitle: 'shortDescription',
      media: 'heroImage',
    },
  },
});
